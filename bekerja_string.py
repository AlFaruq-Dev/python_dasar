nama = "python dasar"
print(len(nama))                    # len() untuk menghitung jumlah karakter
print(nama.upper())                 # upper() untuk mengubah huruf menjadi kapital 
print(nama.lower())                 # lower() untuk mengubah huruf menjadi kecil
print(nama[0:6])                    # slicing untuk mengambil karakter dari index 0 sampai 5
print(nama.split(" "))              # split() untuk memisahkan string menjadi list

bab = 2
print(f"Belajar {nama} bab {bab}")  #f-string untuk menampilkan variabel dalam string